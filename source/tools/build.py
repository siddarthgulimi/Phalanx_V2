"""Builds both Phalanx editions (Original + Pink) from ONE source tree.

The only per-edition inputs are themes/<edition>/palette.css, the icons and the
edition descriptor below, so functionality is identical by construction.

Output (dist/):
  Phalanx-Original.zip / Phalanx-Pink.zip, each containing
    Phalanx-Setup.exe   Windows installer
    Phalanx.exe         portable desktop app (run directly)
    extension/          Chrome / Edge extension (Load unpacked)
    source/             full source (Go engine, web UI, extension, build tools)
    README.md, INSTALL.txt
Usage: python3 tools/build.py [--linux]   (--linux also builds a Linux engine for testing)
"""
import json, os, pathlib, shutil, subprocess, sys, zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
BUILD = ROOT / "build"
EDITIONS = {
    "original": {"label": "Original", "folder": "Phalanx-Original", "accents": [["green", "Green"], ["amber", "Amber"]], "defaultAccent": "green"},
    "pink": {"label": "Pink", "folder": "Phalanx-Pink", "accents": [["rose", "Rose"], ["lavender", "Lavender"]], "defaultAccent": "rose"},
}
SHARED_JS = ["intel.js", "analysis.js", "report-view.js"]


def edition_js(name, ed):
    desc = {"name": name, "label": ed["label"], "accents": ed["accents"], "defaultAccent": ed["defaultAccent"]}
    return (
        "/* Generated by tools/build.py: edition descriptor + theme applier. */\n"
        "(function (root) {\n"
        f"  root.PHALANX_EDITION = {json.dumps(desc)};\n"
        "  root.phalanxApplyTheme = function (cfg) {\n"
        "    if (typeof document === 'undefined' || !cfg) return;\n"
        "    var t = cfg.theme || 'dark';\n"
        "    if (t === 'system') t = (root.matchMedia && root.matchMedia('(prefers-color-scheme: light)').matches) ? 'light' : 'dark';\n"
        "    var r = document.documentElement;\n"
        "    r.setAttribute('data-theme', t);\n"
        "    r.setAttribute('data-accent', cfg.accent || root.PHALANX_EDITION.defaultAccent);\n"
        "    r.setAttribute('data-size', cfg.size || 'normal');\n"
        "  };\n"
        "})(typeof self !== 'undefined' ? self : window);\n"
    )


def copy_shared(dst, name, ed):
    dst.mkdir(parents=True, exist_ok=True)
    for f in SHARED_JS + ["ui.css"]:
        shutil.copy(ROOT / "shared" / f, dst / f)
    shutil.copy(ROOT / "themes" / name / "palette.css", dst / "palette.css")
    (dst / "edition.js").write_text(edition_js(name, ed), encoding="utf-8")


def build_extension(name, ed, out):
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(ROOT / "extension", out, ignore=shutil.ignore_patterns("lib", "icons"))
    copy_shared(out / "lib", name, ed)
    (out / "icons").mkdir()
    for s in (16, 32, 48, 128):
        shutil.copy(ROOT / "themes" / name / "icons" / f"icon{s}.png", out / "icons" / f"icon{s}.png")
    if name != "original":
        m = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
        m["name"] = m["name"] + f" ({ed['label']})"
        (out / "manifest.json").write_text(json.dumps(m, indent=2, ensure_ascii=False), encoding="utf-8")


def build_engine(name, ed, out_dir, linux=False):
    stage = BUILD / f"engine-{name}"
    if stage.exists():
        shutil.rmtree(stage)
    shutil.copytree(ROOT / "engine", stage)
    copy_shared(stage / "web" / "shared", name, ed)
    (stage / "web" / "img").mkdir(exist_ok=True)
    shutil.copy(ROOT / "themes" / name / "icons" / "icon128.png", stage / "web" / "img" / "icon.png")
    # Windows resources: icon + version info
    ico = ROOT / "themes" / name / "icons" / "icon.ico"
    rc = stage / "phalanx.rc"
    rc.write_text(
        f'1 ICON "{ico.as_posix()}"\n'
        '1 VERSIONINFO\nFILEVERSION 2,0,0,0\nPRODUCTVERSION 2,0,0,0\nBEGIN\n BLOCK "StringFileInfo"\n BEGIN\n  BLOCK "040904B0"\n  BEGIN\n'
        f'   VALUE "FileDescription", "Phalanx desktop engine ({ed["label"]} edition)"\n'
        '   VALUE "ProductName", "Phalanx"\n   VALUE "FileVersion", "2.0.0"\n   VALUE "ProductVersion", "2.0.0"\n'
        '   VALUE "OriginalFilename", "Phalanx.exe"\n  END\n END\n BLOCK "VarFileInfo"\n BEGIN\n  VALUE "Translation", 0x409, 1200\n END\nEND\n',
        encoding="utf-8")
    subprocess.run(["x86_64-w64-mingw32-windres", "--preprocessor=cpp", "-O", "coff", "-i", str(rc), "-o", str(stage / "rsrc_windows_amd64.syso")], check=True)
    env = dict(os.environ, CGO_ENABLED="0", GOOS="windows", GOARCH="amd64", GOFLAGS="-trimpath")
    ld = f"-H windowsgui -s -w -X main.edition={name}"
    subprocess.run(["go", "build", "-ldflags", ld, "-o", str(out_dir / "Phalanx.exe"), "."], cwd=stage, env=env, check=True)
    if linux:
        env = dict(os.environ, CGO_ENABLED="0", GOOS="linux", GOARCH="amd64")
        subprocess.run(["go", "build", "-ldflags", f"-s -w -X main.edition={name}", "-o", str(BUILD / f"phalanx-linux-{name}"), "."], cwd=stage, env=env, check=True)


def write_docs(name, ed, out):
    readme = (ROOT / "docs" / "README.md").read_text(encoding="utf-8").replace("{{EDITION}}", ed["label"])
    (out / "README.md").write_text(readme, encoding="utf-8")
    inst = (ROOT / "docs" / "INSTALL.txt").read_text(encoding="utf-8").replace("{{EDITION}}", ed["label"])
    (out / "INSTALL.txt").write_text(inst.replace("\n", "\r\n"), encoding="utf-8")


def copy_source(out):
    src = out / "source"
    ignore = shutil.ignore_patterns("dist", "build", "__pycache__", "*.syso", ".git")
    for d in ("engine", "extension", "shared", "themes", "tools", "installer", "docs"):
        shutil.copytree(ROOT / d, src / d, ignore=ignore)


def zip_dir(folder, zpath):
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(folder.rglob("*")):
            z.write(p, p.relative_to(folder.parent))


def main():
    linux = "--linux" in sys.argv
    DIST.mkdir(exist_ok=True)
    BUILD.mkdir(exist_ok=True)
    subprocess.run([sys.executable, str(ROOT / "tools" / "genpages.py")], check=True)
    for name, ed in EDITIONS.items():
        out = DIST / ed["folder"]
        if out.exists():
            shutil.rmtree(out)
        out.mkdir(parents=True)
        build_extension(name, ed, out / "extension")
        build_engine(name, ed, out, linux)
        write_docs(name, ed, out)
        shutil.copy(ROOT / "themes" / name / "icons" / "icon.ico", out / "icon.ico")
        subprocess.run(["makensis", "-V2", f"-DEDITION={name}", f"-DEDLABEL={ed['label']}", f"-DSRC={out}",
                        f"-DOUT={out / 'Phalanx-Setup.exe'}", str(ROOT / "installer" / "phalanx.nsi")], check=True)
        copy_source(out)
        zp = DIST / (ed["folder"] + ".zip")
        if zp.exists():
            zp.unlink()
        zip_dir(out, zp)
        print(f"built {zp.name}: {zp.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
